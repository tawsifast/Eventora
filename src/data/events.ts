export function getEvent(id: string): Event | undefined {
  return events.find((e) => e.id === id || e.slug === id);
}

export function getFeaturedEvents(): Event[] {
  return events.filter((e) => e.featured);
}

export function getUpcomingEvents(limit?: number): Event[] {
  const sorted = events
    .filter((e) => e.status === "upcoming")
    .sort((a, b) => a.date.localeCompare(b.date));
  return limit ? sorted.slice(0, limit) : sorted;
}

export function getEventsByCategory(slug: string): Event[] {
  return events.filter((e) => e.categorySlug === slug);
}

export function getEventsByOrganizer(organizerId: string): Event[] {
  return events.filter((e) => e.organizerId === organizerId);
}
